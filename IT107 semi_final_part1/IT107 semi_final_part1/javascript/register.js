    // Auto-format helper: title-case per word while typing (uppercase only at word starts)
    function autoTitleCase(el){
        if (!el) return;
        el.addEventListener('input', function(){
            const original = this.value;
            // Collapse multiple spaces but keep single space while typing
            const collapsed = original.replace(/\s{2,}/g, ' ');
            const parts = collapsed.split(' ');
            for (let i = 0; i < parts.length; i++){
                const p = parts[i];
                if (p.length === 0) continue;
                parts[i] = p.charAt(0).toUpperCase() + p.slice(1).toLowerCase();
            }
            const formatted = parts.join(' ');
            if (formatted !== this.value){
                this.value = formatted;
            }
        });
    }

