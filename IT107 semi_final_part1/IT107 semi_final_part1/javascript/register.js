// ✅ Utility function to show error for leading spaces in text input fields (allows space entry)
function preventLeadingSpaceOnInput(inputElement, errorElement) {
    if (!inputElement || !errorElement) return;
    
    inputElement.addEventListener('input', function() {
        if (this.value.length > 0 && this.value[0] === ' ') {
            errorElement.textContent = 'Spaces are not allowed at the beginning.';
            inputElement.classList.add('input-error');
            inputElement.classList.remove('input-success');
        } else {
            // Clear error when space is removed
            if (errorElement.textContent === 'Spaces are not allowed at the beginning.') {
                errorElement.textContent = '';
                inputElement.classList.remove('input-error');
            }
        }
    });
}

