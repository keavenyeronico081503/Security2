function calculateAge() {
    var birthdate = document.getElementById("birthday").value;
    var ageInput = document.getElementById("Age");
    
    if (birthdate) {
        var today = new Date();
        var bday = new Date(birthdate);
        
        // Check if the year is beyond 2025 or if the date is in the future
        const birthYear = bday.getFullYear();
        if (birthYear > 2025 || bday > today) {
            // Show error in birthday field
            const birthdayInput = document.getElementById("birthday");
            const birthdayError = ensureErrorElement('birthdayError', birthdayInput);
            if (birthdayError) {
                birthdayError.textContent = "Age Must not be in a future";
                birthdayInput.classList.add("input-error");
                birthdayInput.classList.remove("input-success");
            }
            // Clear age field
            ageInput.value = "";
            return;
        }

        var age = today.getFullYear() - bday.getFullYear();
        var monthDiff = today.getMonth() - bday.getMonth();

        if (monthDiff < 0 || (monthDiff === 0 && today.getDate() < bday.getDate())) {
            age--;
        }

        ageInput.value = age;
        
        // ✅ Validate age after calculation
        validateAge();
    }
}

