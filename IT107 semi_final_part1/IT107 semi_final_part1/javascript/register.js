// ✅ Helper function for Street validation - allows hyphens and numbers (but not at start)
function findFirstErrorStreet(raw, value, max) {
    const errors = [];
    
    // Check for leading space (position 0)
    if (raw.length > 0 && raw[0] === ' ') {
        errors.push({ position: 0, message: "Spaces are not allowed at the beginning." });
    }
    
    // Check for multiple spaces (find first position)
    const multipleSpacesMatch = raw.match(/\s{2,}/);
    if (multipleSpacesMatch) {
        errors.push({ position: raw.indexOf(multipleSpacesMatch[0]), message: "Double spaces are not allowed." });
    }
    
    // Check for space after hyphen (e.g., "Purok- 3")
    const spaceAfterHyphen = /-\s/.exec(value);
    if (spaceAfterHyphen) {
        errors.push({ position: value.indexOf(spaceAfterHyphen[0]), message: "Remove the space after the hyphen." });
    }
    
    // Check for special characters (find first position) - allow hyphens and numbers
    for (let i = 0; i < raw.length; i++) {
        if (/[^a-zA-Z0-9\s-]/.test(raw[i])) {
            if (/_/.test(raw[i])) {
                errors.push({ position: i, message: "Only letters, spaces, and hyphens are allowed." });
        } else {
                errors.push({ position: i, message: "Special character is not allowed." });
        }
            break;
        }
    }
    
    // Check for lowercase letters after numbers (e.g., "P-3a" should be invalid)
    for (let i = 0; i < value.length - 1; i++) {
        if (/\d/.test(value[i]) && /[a-z]/.test(value[i + 1])) {
            errors.push({ position: i + 1, message: "After a number, letters must be uppercase." });
            break;
        }
    }
    
    // Check for trailing hyphen FIRST (higher priority)
    if (value.endsWith('-')) {
        errors.push({ position: value.length - 1, message: "Street cannot end with a hyphen." });
    }
    
    // Check for trailing space
    if (raw.endsWith(' ') && raw.trim().length > 0) {
        errors.push({ position: raw.length - 1, message: "Cannot end with a space." });
    }
    
    // Check for consecutive letters
    const consecutiveMatch = value.match(/(.)\1{2,}/i);
    if (consecutiveMatch) {
        errors.push({ position: value.indexOf(consecutiveMatch[0]), message: "Three (3) consecutive letters are not allowed." });
    }
    
    // Check for all caps (only if length >= 4 and no hyphen at end) - more lenient for short inputs
    if (value === value.toUpperCase() && value.length >= 4 && /^[A-Z\s\-]+$/.test(value) && !value.endsWith('-')) {
        errors.push({ position: 0, message: "All capital letters are not allowed in Street." });
    }
    
    // Check for consecutive capitals
    const consecutiveCapMatch = value.match(/([A-Z][A-Z])/);
    if (consecutiveCapMatch) {
        errors.push({ position: value.indexOf(consecutiveCapMatch[0]), message: "Consecutive capital letters are not allowed." });
    }
    
    // Disallow ordinal numbers (e.g., 12th, 3rd) anywhere in the input
    // Also catch truncated ordinals like "12t", "3r", "2n", "1s" and any single-letter suffix (e.g., "3324r")
    const ordinalMatch = raw.match(/\b\d+(?:st|nd|rd|th|[A-Za-z])\b/i);
    if (ordinalMatch) {
        const matchText = ordinalMatch[0];
        const matchPos = raw.indexOf(matchText);
        // Allow patterns like: Word-3A (e.g., "Purok-3A") where there is a letter, a hyphen,
        // then the digits+single UPPERCASE letter — treat these as valid unit/lot identifiers.
        const beforeIdx = matchPos - 1;
        const twoBeforeIdx = matchPos - 2;
        const afterChar = raw.charAt(matchPos + matchText.length - 1);

        const isPrefixedByLetterHyphen = (
            beforeIdx >= 0 && twoBeforeIdx >= 0 &&
            raw.charAt(beforeIdx) === '-' && /[A-Za-z]/.test(raw.charAt(twoBeforeIdx))
        );

        if (!(isPrefixedByLetterHyphen && /[A-Z]/.test(afterChar))) {
            errors.push({ position: matchPos, message: "No ordinal numbers; use numbers with street name (e.g., 12 Street)." });
        }
    }

    // Check if the input is numbers only (allow spaces and hyphens between numbers)
    const strippedForDigits = raw.replace(/[\s-]/g, '');
    if (strippedForDigits.length > 0 && /^\d+$/.test(strippedForDigits)) {
        errors.push({ position: 0, message: "Street/Purok must include words after the number." });
    }
    
    // Check for max length
    if (value.length >= max) {
        errors.push({ position: max, message: `Maximum ${max} characters reached.` });
    }
    
    // Check capitalization errors: only require first letter capitalized if the field starts with a letter
    if (value.length > 0) {
        if (/^[A-Za-z]/.test(value) && !/^[A-Z]/.test(value)) {
            errors.push({ position: 0, message: "Street must start with a capital letter." });
        } else {
            const parts = value.split(/\s+/).filter(Boolean);
            if (parts.length >= 2 && /^[A-Za-z]/.test(parts[1]) && /^[a-z]/.test(parts[1])) {
                const secondWordStart = value.indexOf(parts[1]);
                errors.push({ position: secondWordStart, message: "The second word must start with a capital letter." });
            }
        }
    }
    
    if (errors.length > 0) {
        errors.sort((a, b) => a.position - b.position);
        return errors[0].message;
    }
    
    return null;
}

