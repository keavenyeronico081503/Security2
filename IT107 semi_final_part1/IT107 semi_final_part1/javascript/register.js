    // ✅ Helper function to find the first error in input (left to right)
function findFirstError(raw, value, max, allowHyphens = false) {
    const errors = [];
    
    // Check for leading space (position 0)
    if (raw.length > 0 && raw[0] === ' ') {
        errors.push({ position: 0, message: "Spaces are not allowed at the beginning." });
    }
    
    // Check for hyphen (find first position) - only if not allowed
    if (!allowHyphens) {
        const hyphenIndex = raw.indexOf('-');
        if (hyphenIndex !== -1) {
            errors.push({ position: hyphenIndex, message: "Hyphens are not allowed in this field." });
        }
    }
    
    // Check for multiple spaces (find first position)
    const multipleSpacesMatch = raw.match(/\s{2,}/);
    if (multipleSpacesMatch) {
        errors.push({ position: raw.indexOf(multipleSpacesMatch[0]), message: "Double spaces are not allowed." });
    }
    
    // Check for digits (find first position) - check in raw to get correct position
    for (let i = 0; i < raw.length; i++) {
        if (/\d/.test(raw[i])) {
            errors.push({ position: i, message: "Numbers are not allowed." });
            break;
        }
    }
    
    // Check for special characters (find first position) - only true special chars, not digits
    // This should come after digit check so digits are caught first
    for (let i = 0; i < raw.length; i++) {
        if (/[^a-zA-Z0-9\s]/.test(raw[i])) {
            errors.push({ position: i, message: "Special characters are not allowed." });
            break;
        }
    }

    // Check for trailing space (last position) - but only if no other errors found earlier
    if (raw.endsWith(' ') && raw.trim().length > 0) {
        errors.push({ position: raw.length - 1, message: "Cannot end with a space." });
    }
    
    // Check for consecutive letters (find first position)
    const consecutiveMatch = value.match(/(.)\1{2,}/i);
    if (consecutiveMatch) {
        const matchPos = value.indexOf(consecutiveMatch[0]);
        errors.push({ position: matchPos, message: "Three (3) consecutive letters are not allowed." });
    }

    // Check for all caps (affects whole string, but check after other errors)
    if (value === value.toUpperCase() && value.length >= 2) {
        errors.push({ position: 0, message: "All capital letters are not allowed." });
    }
    
    // Check for consecutive capitals (find first position)
    const consecutiveCapMatch = value.match(/([A-Z][A-Z])/);
    if (consecutiveCapMatch) {
        errors.push({ position: value.indexOf(consecutiveCapMatch[0]), message: "Consecutive capital letters are not allowed." });
    }
    
    // Check for max length (affects end, but check after other errors)
    if (value.length >= max) {
        errors.push({ position: max, message: `Maximum ${max} characters reached.` });
    }
    
    // Check capitalization errors (find first position)
    if (value.length > 0) {
        if (value[0] !== value[0].toUpperCase()) {
            errors.push({ position: 0, message: "Must start with a capital letter." });
        } else {
            const parts = value.split(/\s+/).filter(Boolean);
            if (parts.length >= 2 && parts[1] && parts[1].charAt(0) !== parts[1].charAt(0).toUpperCase()) {
                const secondWordStart = value.indexOf(parts[1]);
                errors.push({ position: secondWordStart, message: "The second word must start with a capital letter." });
            } else {
                // Check for other capitalization issues
                for (let i = 0; i < value.length; i++) {
                    const char = value[i];
                    if (i === 0 || value[i-1] === ' ') {
                        // Should be uppercase
                        if (/[a-z]/.test(char)) {
                            errors.push({ position: i, message: `'${char}' should be uppercase` });
                            break;
                        }
                    } else if (/[a-zA-Z]/.test(value[i-1]) && /[A-Z]/.test(char) && !/[A-Z]/.test(value[i-1])) {
                        // Middle of word should be lowercase
                        errors.push({ position: i, message: `'${char}' should be lowercase` });
                        break;
                    }
                }
            }
        }
    }
    
    // Return the error with the smallest position (leftmost error)
    if (errors.length > 0) {
        errors.sort((a, b) => a.position - b.position);
        return errors[0].message;
    }
    
    return null;
}

// ✅ Real-time validation with min & max limit - Shows FIRST error from left to right
function validateFname() {
    const input = document.getElementById("fname");
    const error = document.getElementById("fnameError");
    const raw = input.value;
    const value = raw.trim();
    const min = parseInt(input.getAttribute("minlength"));
    const max = parseInt(input.getAttribute("maxlength"));
    const pattern = /^([A-Z][a-z]*)(\s[A-Z][a-z]*)*$/; // Only letters and spaces with proper title case
    
    // ✅ Check if empty first
    if (value === "") {
        error.textContent = "First Name is required.";
        input.classList.add("input-error");
        input.classList.remove("input-success");
        return;
    }
    
    // ✅ Find the first error from left to right
    const firstError = findFirstError(raw, value, max);
    
    if (firstError) {
        error.textContent = firstError;
        input.classList.add("input-error");
        input.classList.remove("input-success");
    
        // Handle max length by truncating
        if (firstError.includes("Maximum")) {
        input.value = value.substring(0, max);
        }
        return;
    }
    
    // ✅ Final pattern check
    if (!pattern.test(value)) {
        const parts = value.split(/\s+/).filter(Boolean);
        if (value.length > 0 && value[0] !== value[0].toUpperCase()) {
            error.textContent = "Must start with a capital letter.";
        } else if (parts.length >= 2 && parts[1] && parts[1].charAt(0) !== parts[1].charAt(0).toUpperCase()) {
            error.textContent = "The second word must start with a capital letter.";
        } else {
            const incorrectChars = checkCapitalization(value);
            if (incorrectChars.length > 0) {
                error.textContent = incorrectChars.join(", ");
            } else {
                error.textContent = "Each word should start with a capital letter only.";
            }
        }
        input.classList.add("input-error");
        input.classList.remove("input-success");
        return;
    }
    
    // ✅ SUCCESS: No errors found
    error.textContent = "";
    input.classList.remove("input-error");
    input.classList.add("input-success");
}
