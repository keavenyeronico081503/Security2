<?php
// Builds database/024_address_data.sql from the public PSGC dataset
// (https://psgc.gitlab.io/api), so the address dropdowns work offline.
//
// Usage: php build_psgc_sql.php <download-dir> <output.sql>
// <download-dir> must contain regions.json, provinces.json,
// cities-municipalities.json and barangays.json from the API above.

[$script, $dir, $out] = $argv + [null, null, null];
if (!$dir || !$out) {
    fwrite(STDERR, "Usage: php build_psgc_sql.php <download-dir> <output.sql>\n");
    exit(2);
}

function load_json(string $path): array
{
    $data = json_decode((string)file_get_contents($path), true);
    if (!is_array($data)) {
        fwrite(STDERR, "Could not read $path\n");
        exit(1);
    }
    return $data;
}

function code(mixed $value): string
{
    $value = (string)$value;
    if (!preg_match('/^[0-9A-Z]{1,12}$/', $value)) {
        fwrite(STDERR, "Unexpected code: $value\n");
        exit(1);
    }
    return $value;
}

function sql_string(string $value): string
{
    return "'" . str_replace(["\\", "'"], ["\\\\", "''"], $value) . "'";
}

function write_inserts($fh, string $table, array $columns, array $rows): void
{
    foreach (array_chunk($rows, 500) as $chunk) {
        $values = array_map(fn($row) => '(' . implode(', ', array_map('sql_string', $row)) . ')', $chunk);
        fwrite($fh, "INSERT INTO $table (" . implode(', ', $columns) . ") VALUES\n" . implode(",\n", $values) . ";\n");
    }
}

$regions = load_json("$dir/regions.json");
$provinces = load_json("$dir/provinces.json");
$cities = load_json("$dir/cities-municipalities.json");
$barangays = load_json("$dir/barangays.json");

$regionRows = [];
$regionNames = [];
foreach ($regions as $region) {
    $label = $region['regionName'] && $region['regionName'] !== $region['name']
        ? "{$region['regionName']} - {$region['name']}"
        : $region['name'];
    $regionRows[] = [code($region['code']), $label];
    $regionNames[$region['code']] = $label;
}

$provinceRows = [];
foreach ($provinces as $province) {
    $provinceRows[] = [code($province['code']), $province['name'], code($province['regionCode'])];
}

// Cities that belong to no province (all of NCR, plus a few independent cities)
// get one pseudo-province per region so the dropdown chain never has a gap.
$pseudoProvinces = [];
$cityRows = [];
foreach ($cities as $city) {
    $regionCode = code($city['regionCode']);
    $provinceCode = $city['provinceCode'] ? code($city['provinceCode']) : null;
    if ($provinceCode === null) {
        $provinceCode = 'X' . $regionCode;
        $pseudoProvinces[$provinceCode] = [
            $provinceCode,
            stripos($regionNames[$regionCode] ?? '', 'National Capital') !== false ? 'Metro Manila' : 'Independent cities',
            $regionCode,
        ];
    }
    $cityRows[] = [code($city['code']), $city['name'], $provinceCode, $regionCode];
}
$provinceRows = array_merge($provinceRows, array_values($pseudoProvinces));

$barangayRows = [];
foreach ($barangays as $barangay) {
    $cityCode = $barangay['cityCode'] ?: $barangay['municipalityCode'];
    $barangayRows[] = [code($barangay['code']), $barangay['name'], code($cityCode)];
}

$fh = fopen($out, 'w');
fwrite($fh, "-- Philippine Standard Geographic Code (PSGC) data for the address dropdowns.\n");
fwrite($fh, "-- Generated by database/tools/build_psgc_sql.php from https://psgc.gitlab.io/api\n");
fwrite($fh, "-- " . count($regionRows) . " regions, " . count($provinceRows) . " provinces (incl. pseudo), "
    . count($cityRows) . " cities/municipalities, " . count($barangayRows) . " barangays.\n\n");
fwrite($fh, "SET NAMES utf8mb4;\nDELETE FROM address_barangays;\nDELETE FROM address_cities;\nDELETE FROM address_provinces;\nDELETE FROM address_regions;\n\n");
write_inserts($fh, 'address_regions', ['code', 'name'], $regionRows);
write_inserts($fh, 'address_provinces', ['code', 'name', 'region_code'], $provinceRows);
write_inserts($fh, 'address_cities', ['code', 'name', 'province_code', 'region_code'], $cityRows);
write_inserts($fh, 'address_barangays', ['code', 'name', 'city_code'], $barangayRows);
fclose($fh);

echo count($regionRows) . " regions, " . count($provinceRows) . " provinces, " . count($cityRows) . " cities, " . count($barangayRows) . " barangays\n";
